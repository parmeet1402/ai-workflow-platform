CREATE OR REPLACE FUNCTION "public"."worker_fail_document_processing"("p_document_id" "uuid", "p_organization_id" "uuid", "p_error" "text") RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  safe text := left(coalesce(p_error, 'unknown error'), 2000);
BEGIN
  UPDATE public.documents
  SET
    processing_status = 'failed',
    processing_error = safe
  WHERE id = p_document_id
    AND organization_id = p_organization_id
    AND processing_status = 'processing';
END;
$$;


