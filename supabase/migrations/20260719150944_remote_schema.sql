CREATE OR REPLACE FUNCTION "public"."worker_finalize_document_ingest"("p_document_id" "uuid", "p_organization_id" "uuid", "p_chunks" "jsonb") RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  doc_org uuid;
  st text;
BEGIN
  SELECT organization_id, processing_status
  INTO doc_org, st
  FROM public.documents
  WHERE id = p_document_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'document not found';
  END IF;

  IF doc_org IS DISTINCT FROM p_organization_id THEN
    RAISE EXCEPTION 'organization mismatch';
  END IF;

  IF st IS DISTINCT FROM 'processing' THEN
    RAISE EXCEPTION 'document not in processing state: %', st;
  END IF;

  DELETE FROM public.document_chunks WHERE document_id = p_document_id;

  INSERT INTO public.document_chunks (document_id, chunk_index, content, metadata, embedding)
  SELECT
    p_document_id,
    (elem->>'chunk_index')::integer,
    elem->>'content',
    COALESCE(elem->'metadata', '{}'::jsonb),
    ((elem->'embedding')::text)::vector(1536)
  FROM jsonb_array_elements(p_chunks) AS elem;

  UPDATE public.documents
  SET
    processing_status = 'ready',
    processed_at = now(),
    processing_error = null
  WHERE id = p_document_id;
END;
$$;


